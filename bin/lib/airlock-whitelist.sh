#!/usr/bin/env bash
#
# airlock-whitelist.sh — owns the egress list a project actually gets: which blocks
# in proxy/whitelist.d/ compose it, the reduction squid's dstdomain parser requires,
# and the marker that says whether the running proxy has read the current list.
#
# proxy/squid.conf carries no domains at all (0015); this file is where the list
# comes from. What a STACK contributes is derived from its components by
# airlock-kit.sh, so the blocks and the image cannot disagree.
#
# Sourced, defines functions only. Callers provide $NAME, $HARNESS_DIR, $CTL,
# $STACK, $COMPONENTS, $HARNESS and $WHITELIST.

# ── the egress whitelist, composed per project ────────────────────────────────
# proxy/squid.conf carries no domains at all any more (it is policy + one include),
# so the list the proxy enforces is the file built here, at every launch, out of the
# blocks in proxy/whitelist.d/:
#
#     the blocks for the project's STACK (or its COMPONENTS=, which wins)
#   + the one block for its HARNESS
#   + the project's own WHITELIST= entries
#
# It is written into the CONTROL DIR: the file is mounted into the proxy, so writing
# it next to the project would hand the agent its own egress list.
WL_BLOCKS=""        # which blocks went in — printed on the launch line
WL_COUNT=0          # how many domains came out of the de-duplication

# STACK → its blocks, derived from the very components airlock.json installs into the
# image (kit_stack_blocks): node → npm, python → PyPI, java → the JVM ecosystem,
# dotnet → NuGet. 0015 kept a second hard-coded table here, which could drift from
# the Dockerfiles; there is one table now, and it is the one that decides the build.
# Note that `dotnet` has no python component, so a .NET project gets no PyPI — a
# project that needs it says so in its own WHITELIST=. A project's COMPONENTS=
# overrides the stack's set here exactly as it does for the build args.
stack_blocks() { kit_stack_blocks "$1" "${COMPONENTS:-}"; }

# HARNESS → its vendor block. One harness per project (0014), so one block.
harness_block() { echo "harness-$1"; }

# squid REFUSES to start on a duplicate dstdomain entry, and warns on one that a
# broader entry already covers (`github.com` under `.github.com`) — and blocks are
# meant to overlap (stack-java and harness-copilot both want .githubusercontent.com).
# So reduce the union here: keep first occurrences, then drop every entry some OTHER
# `.domain` entry already covers.
wl_reduce() {
  awk '
    /^[[:space:]]*(#|$)/ { next }
    { gsub(/^[[:space:]]+|[[:space:]]+$/, ""); if ($0 == "") next }
    !seen[$0]++ { d[n++] = $0 }
    END {
      for (i = 0; i < n; i++) if (substr(d[i], 1, 1) == ".") w[substr(d[i], 2)] = 1
      for (i = 0; i < n; i++) {
        s = d[i]; drop = 0
        base = (substr(s, 1, 1) == ".") ? substr(s, 2) : s
        for (x in w) {
          if (x == base) { if (s != "." x) { drop = 1; break }; continue }
          if (length(base) > length(x) && substr(base, length(base) - length(x)) == "." x) { drop = 1; break }
        }
        if (!drop) print s
      }
    }'
}

build_whitelist() {
  local wl="$CTL/whitelist.txt" tmp="$CTL/whitelist.txt.new" b f d
  WL_BLOCKS="$(stack_blocks "$STACK") $(harness_block "$HARNESS")"
  [[ -n "${WHITELIST:-}" ]] && WL_BLOCKS="$WL_BLOCKS project"
  {
    for b in $WL_BLOCKS; do
      [[ "$b" == "project" ]] && continue
      f="$HARNESS_DIR/proxy/whitelist.d/$b.txt"
      if [[ -f "$f" ]]; then cat "$f"; else
        echo "$NAME: no whitelist block proxy/whitelist.d/$b.txt — skipped." >&2
      fi
    done
    if [[ -n "${WHITELIST:-}" ]]; then
      set -f
      for d in $WHITELIST; do echo "$d"; done
      set +f
    fi
  } | wl_reduce > "$tmp"
  WL_COUNT="$(grep -c . "$tmp" | tr -d ' ')"
  {
    echo "# Generated by $NAME for $PWD — do not edit by hand; it is rewritten at every"
    echo "# launch. Sources: proxy/whitelist.d/{$(echo $WL_BLOCKS | tr ' ' ',')}"
    echo "# and WHITELIST= in $CTL/config. squid.conf carries no domains of its own."
    cat "$tmp"
  } > "$wl"
  rm -f "$tmp"
  export EXTRA_WHITELIST="$wl"

  # A changed list only takes effect once squid re-reads it. Remember what the
  # running proxy was started with (bin/harness updates this marker after it has
  # actually reloaded) and ask for a reload when the content moved.
  if [[ ! -f "$CTL/whitelist.applied" ]] || ! cmp -s "$wl" "$CTL/whitelist.applied"; then
    export AIRLOCK_PROXY_RELOAD=1
  fi
}
